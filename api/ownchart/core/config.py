from functools import lru_cache
from pathlib import Path

from pydantic import Field, SecretStr
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_prefix="OWNCHART_",
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
    )

    env: str = Field(default="dev", description="dev | prod")
    debug_payloads: bool = Field(
        default=False,
        description="If True, raw request/response bodies may be logged. PHI risk.",
    )

    database_url: str = Field(
        default="postgresql+asyncpg://ownchart:ownchart@postgres:5432/ownchart"
    )
    redis_url: str = Field(default="redis://redis:6379/0")

    session_secret: SecretStr = Field(
        default=SecretStr("change-me-in-env"),
        description="Used to sign httpOnly session cookies. Set in infra/.env.",
    )
    session_cookie_name: str = "ownchart_session"
    session_max_age_seconds: int = 60 * 60 * 24 * 14

    data_dir: Path = Field(default=Path("/data"))

    anthropic_api_key: SecretStr | None = Field(default=None)
    anthropic_default_model: str = Field(default="claude-opus-4-7")
    anthropic_vision_model: str = Field(default="claude-opus-4-7")

    # SMTP credential for outbound transactional email (invites, password
    # reset, email verification). The non-secret SMTP settings (host, port,
    # use_tls, username, from_address) live in infra/config.yaml under
    # `smtp:` (see core/app_config.py::SmtpConfig); only the password is a
    # Tier-1 secret. When unset (or smtp.enabled is False in config.yaml),
    # `core.email.send_email` no-ops cleanly so self-hosters without SMTP
    # keep working — the invite-URL-copy fallback stays.
    smtp_password: SecretStr | None = Field(default=None)

    # Password-reset token lifetime. Short by design — a reset link is a
    # single-use bearer credential to the account. 1h default.
    password_reset_token_ttl_seconds: int = Field(default=60 * 60)
    # Email-verification token lifetime. Longer than reset (verification is
    # not credential-equivalent — it only flips a flag). 24h default.
    email_verification_token_ttl_seconds: int = Field(default=60 * 60 * 24)

    # AES-256 data encryption key (base64 32-byte). Used to encrypt OAuth
    # access/refresh tokens at rest. Generated by deploy.sh on first deploy
    # and persisted in infra/.env. Treat as more sensitive than session_secret —
    # losing it means re-authenticating every connected provider.
    token_dek: SecretStr | None = Field(default=None)

    # Public base URL used to compose redirect_uris registered with EHRs.
    # Must match what's on file with the provider (e.g. fhir.epic.com app reg).
    # Override with OWNCHART_PUBLIC_BASE_URL on every real deployment.
    public_base_url: str = Field(default="http://localhost:8080")

    # Bearer token for the Health Auto Export iOS app's REST push
    # endpoint. Configure both: (a) here in infra/.env, (b) in the iOS
    # app's Automations → REST API setup, with the same value as the
    # Authorization header. When unset, the push endpoint returns 503
    # so it's not silently open. Single-tenant V1 — multi-user deploys
    # will want per-user tokens instead.
    auto_export_token: SecretStr | None = Field(default=None)

    # Google Calendar OAuth (FU-CAL-GOOGLE-OAUTH).
    # Operator secrets only — never read from config.yaml, never
    # logged, never returned in /api/instance/info. The
    # ``is_google_calendar_configured()`` helper gates the start
    # endpoint; missing config returns 503 ("not configured by this
    # OwnChart operator"), never silently fails open. The redirect
    # URI must exactly match what's registered in the operator's
    # Google Cloud OAuth consent screen, including scheme + path.
    google_calendar_client_id: SecretStr | None = Field(default=None)
    google_calendar_client_secret: SecretStr | None = Field(default=None)
    google_calendar_redirect_uri: str | None = Field(
        default=None,
        description=(
            "Full callback URL registered in Google Cloud. Example: "
            "https://ownchart.your-instance.example.com"
            "/api/calendar/google/callback"
        ),
    )

    cors_allow_origins: list[str] = Field(default_factory=list)

    # Demo mode (demo.ownchart.me). When True, the API rejects every
    # mutating request (POST / PATCH / PUT / DELETE) outside the
    # allowlist with HTTP 403. Lets us run a public read-only
    # instance against the Epic FHIR sandbox without risk of writes.
    # Pairs with a visible "Demo · sample data" banner on the web.
    demo_mode: bool = Field(default=False)
    # Demo seed credentials. Public on purpose — the demo instance is
    # designed for anonymous read-only browsing. Don't ever turn these
    # into real PHI accounts.
    demo_user_email: str = Field(default="demo@ownchart.me")
    demo_user_password: SecretStr = Field(default=SecretStr("MYHEALTHdata"))
    # Temporary escape hatch: when demo_mode AND demo_allow_ingest are
    # both True, the read-only middleware widens its allowlist to
    # permit ingestion endpoints (/api/connectors, /api/sources,
    # /api/healthkit, /api/auto-export). Use this when the operator
    # wants to SMART-on-FHIR connect a sandbox account and ingest
    # synthetic data through the standard UI flow. The "Demo" banner
    # stays visible while it's on so users still know it's a demo.
    demo_allow_ingest: bool = Field(default=False)

    # --- Auth rate limiting (HIGH-7 — Lapland tenant launch gate) -------
    #
    # Per-IP (and, where an identifier exists, per-email) throttles on the
    # credential-facing endpoints: login, device/pair, register, and the
    # unauthenticated invitations/preview. Backed by Redis (shared with
    # arq) so the limit holds across api workers; falls back to an
    # in-process counter only when Redis is unreachable (single-process
    # dev). Fixed-window counters — the Nth+1 attempt inside the window
    # gets a 429 with Retry-After.
    rate_limit_enabled: bool = Field(default=True)
    # Login / pair / register share these defaults. Ten tries per five
    # minutes per IP is generous for a human, punishing for a bot.
    rate_limit_auth_max_attempts: int = Field(default=10)
    rate_limit_auth_window_seconds: int = Field(default=300)
    # invitations/preview is unauthenticated and enumeration-shaped
    # (an attacker probing tokens), so it gets its own, tighter bucket.
    rate_limit_invite_preview_max_attempts: int = Field(default=20)
    rate_limit_invite_preview_window_seconds: int = Field(default=300)

    # --- Demo AI budget (G-1 — public-demo Ask/EI cost guardrail) -------
    #
    # G-1 enables the AI assistant (Ask + Episode Intelligence) on the
    # SHARED public demo account so App Store reviewers can exercise it.
    # That points anonymous public-demo traffic at a real, billed LLM, so
    # we cap cost-bearing AI calls per visitor session AND per source IP
    # per rolling day. Enforced ONLY when demo_mode is on, ON TOP OF the
    # generic auth limiter above (same Redis-backed fixed-window counter,
    # 86400s window). Over-budget → 429 with a friendly, demo-aware
    # message. Per-session is the tight human bound; per-IP is looser so
    # one NAT/office can't drain the whole day for everyone behind it.
    demo_ai_daily_cap_per_session: int = Field(default=10)
    demo_ai_daily_cap_per_ip: int = Field(default=40)
    demo_ai_window_seconds: int = Field(default=60 * 60 * 24)


@lru_cache(maxsize=1)
def get_settings() -> Settings:
    return Settings()
